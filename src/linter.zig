const std = @import("std");
const assert = std.debug.assert;
const scylla = @import("scylla");
const languages = @import("languages.zig");
const Analysis = @import("analysis.zig");
const Diagnostics = scylla.Diagnostics;
const Document = @import("document.zig");
const Fixes = scylla.Fixes;
const Limits = @import("limits.zig");
const Rules = @import("rules.zig");
const Settings = @import("settings.zig");
const TextDocument = scylla.TextDocument;

analysis: Analysis,
document: Document,
rules: Rules,
settings: Settings,

const Linter = @This();

pub const Capacity = struct {
    analysis: Analysis.Capacity,
    document: Document.Capacity,

    pub const default: Capacity = .{
        .analysis = Limits.default.analysis(),
        .document = Limits.default.document(),
    };
};

pub const Source = struct {
    path: []const u8,
    text: []const u8,
};

pub const CapacityError = TextDocument.CapacityError || TextDocument.UriError;
pub const InputError = TextDocument.SyntaxError || error{LanguageUnknown};
pub const Error = CapacityError || InputError;

pub fn init(
    linter: *Linter,
    gpa: std.mem.Allocator,
    io: std.Io,
    capacity: *const Capacity,
) std.mem.Allocator.Error!void {
    assert(capacity.document.diagnostic_count_max > 0);
    assert(capacity.analysis.fixes.fix_count_max > 0);

    linter.rules = try .init(gpa);
    errdefer linter.rules.deinit(gpa);

    try linter.analysis.init(gpa, io, &capacity.analysis);
    errdefer linter.analysis.deinit(gpa);

    linter.document = try .init(gpa, &capacity.document);
    linter.settings = .default;
    linter.settings.rules = linter.rules.defaults();

    assert(!linter.settings.rules.is_empty());
}

pub fn deinit(linter: *Linter, gpa: std.mem.Allocator) void {
    assert(linter.rules.count() > 0);

    linter.document.deinit(gpa);
    linter.analysis.deinit(gpa);
    linter.rules.deinit(gpa);
    linter.* = undefined;
}

pub fn fixes(linter: *const Linter) *const Fixes {
    assert(linter.rules.count() > 0);

    return &linter.analysis.fixes;
}

pub fn lint(linter: *Linter, source: *const Source) Error!*const Diagnostics {
    const language = languages.of_path(source.path) orelse return error.LanguageUnknown;

    assert(languages.linted_set.contains(language));

    linter.document.reset();

    try linter.document.text.uri_set(source.path);
    try linter.document.text.text_replace(source.text);

    linter.document.state.language = language;

    linter.analysis.run(linter.document.entry(), &linter.rules, &linter.settings);

    const diagnostics = &linter.document.state.diagnostics;

    assert(diagnostics.count() <= diagnostics.capacity());

    return diagnostics;
}

test Linter {
    const gpa = std.testing.allocator;
    const source = "fn read_sector() {\n    loop {\n        let value = 1;\n    }\n}\n";
    const linter = try gpa.create(Linter);
    defer gpa.destroy(linter);

    try linter.init(gpa, std.testing.io, &.default);
    defer linter.deinit(gpa);

    const diagnostics = try linter.lint(&.{ .path = "src/sector.rs", .text = source });
    var bounded_loop = false;

    for (diagnostics.slice()) |*diagnostic| {
        if (std.mem.eql(u8, diagnostic.code, "TS006")) bounded_loop = true;

        try std.testing.expect(diagnostics.message_of(diagnostic).len > 0);
    }

    try std.testing.expect(bounded_loop);

    const notes: Source = .{ .path = "notes.txt", .text = source };
    const invalid: Source = .{ .path = "a.rs", .text = "fn \xff() {}\n" };

    try std.testing.expectError(error.LanguageUnknown, linter.lint(&notes));
    try std.testing.expectError(error.Utf8Invalid, linter.lint(&invalid));
}

test lint {
    const gpa = std.testing.allocator;
    const linter = try gpa.create(Linter);
    defer gpa.destroy(linter);

    try linter.init(gpa, std.testing.io, &.default);
    defer linter.deinit(gpa);

    const text = "def add(left, right):\n    return left + right\n";
    const clean = try linter.lint(&.{ .path = "a.py", .text = text });

    try std.testing.expect(clean.empty());

    const generated = "// Code generated by tool. DO NOT EDIT.\nfn main() { loop {} }\n";

    try std.testing.expect((try linter.lint(&.{ .path = "b.rs", .text = generated })).empty());
    try std.testing.expectEqual(@as(u32, 0), linter.fixes().count());
}
